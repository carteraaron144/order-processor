-- Order processor schema (built from solution.md).
-- Run with: psql -d order_processor -f schema.sql
-- WARNING: re-running this drops every table and all their data. Fine for development only.

DROP TABLE IF EXISTS failed_orders, order_lines, orders, items CASCADE;
DROP TYPE IF EXISTS order_status, failure_reason;

-- Enums
-- FAILED = processing crashed on this order MAX_ATTEMPTS times; needs a human to look at it.
CREATE TYPE order_status AS ENUM ('PENDING', 'FULFILLED', 'REJECTED', 'FAILED');
CREATE TYPE failure_reason AS ENUM ('INSUFFICIENT_STOCK', 'INVALID_QUANTITY', 'ITEM_NOT_FOUND', 'UNKNOWN_FAILURE');

-- Items: the inventory.
CREATE TABLE items (
    item_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku               VARCHAR(32)   NOT NULL UNIQUE,              -- what customers and orders refer to, e.g. 'A100'
    item_name         VARCHAR(126)  NOT NULL,
    description       VARCHAR(512),
    price             NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    quantity_in_stock INT           NOT NULL CHECK (quantity_in_stock >= 0),  -- safety net: stock can never go negative
    updated_date      TIMESTAMP     NOT NULL DEFAULT now()
);

-- Orders: one row per order. PENDING orders are the processing queue.
CREATE TABLE orders (
    order_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_time   TIMESTAMP    NOT NULL DEFAULT now(),
    order_status order_status NOT NULL DEFAULT 'PENDING',
    attempts     INT          NOT NULL DEFAULT 0,   -- how many times processing crashed on this order
    last_error   TEXT                               -- the most recent crash, for whoever investigates
);

-- Order lines: only valid lines are stored (unknown items and quantity <= 0 are rejected at intake).
CREATE TABLE order_lines (
    line_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   INT            NOT NULL REFERENCES orders (order_id),
    item_id    INT            NOT NULL REFERENCES items (item_id),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),   -- price at time of sale
    quantity   INT            NOT NULL CHECK (quantity > 0)
);

-- Failed orders: why a REJECTED order was rejected.
CREATE TABLE failed_orders (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       INT            NOT NULL REFERENCES orders (order_id),
    failure_reason failure_reason NOT NULL
);

-- Indexes for the lookups the processor does most.
CREATE INDEX idx_orders_pending ON orders (order_status, order_time);   -- "next PENDING order, oldest first"
CREATE INDEX idx_order_lines_order ON order_lines (order_id);          -- "all lines for this order"
CREATE INDEX idx_failed_orders_order ON failed_orders (order_id);
